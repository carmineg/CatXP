"""Build CatXP/FactBank.lua from the plain-text fact files in tools/facts/.

One fact per line in each lane file (anatomy.txt, behaviour.txt, ...). tiers.txt holds the facts
of the seventeen cats on the ladder under [Cat Name] headers. Every line is checked (plain ASCII,
20 to 140 characters, a capital first letter, a full stop at the end, no | character) and exact
or near duplicates are dropped, then the Lua file is written with one block per lane.

Usage:  python build_facts.py [addon dir]        (default: ../CatXP next to this script)
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FACTS_DIR = os.path.join(HERE, "facts")
ADDON_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "CatXP")
OUT = os.path.join(ADDON_DIR, "FactBank.lua")

LANES = [
    ("general", "A few classics"),
    ("anatomy", "The body and the senses"),
    ("behaviour", "What cats do and what it means"),
    ("lifecycle", "Kittens, growing up, growing old, health and food"),
    ("breeds", "Breeds and the cat fancy"),
    ("coats_records", "Coats, colours, genetics and records"),
    ("history", "Cats through history"),
    ("famous", "Famous cats"),
    ("wildcats", "The wild cousins"),
    ("culture", "Cats in words, stories, screens and folklore"),
]
TIER_ORDER = [
    "Napping Kitten", "Sleepy Kitten", "Playful Kitten", "House Cat", "Alley Cat", "Wildcat",
    "Bobcat", "Lynx", "Ocelot", "Serval", "Caracal", "Puma", "Leopard", "Jaguar", "Tiger",
    "Cheetah", "Nyan Cat",
]
MAX_LEN = 140
MIN_LEN = 20
PREFIX = 45   # two facts whose first 45 letters agree are taken to be the same fact


def clean(raw):
    line = raw.strip()
    line = re.sub(r"^(\d+[.)]\s*|[-*]\s+)", "", line)      # stray numbering or bullets
    if len(line) >= 2 and line[0] == line[-1] and line[0] in "\"'":
        line = line[1:-1].strip()
    return re.sub(r"\s+", " ", line)


def problem(fact):
    if not fact:
        return "empty"
    if any(ord(c) > 126 or ord(c) < 32 for c in fact):
        return "not plain ASCII"
    if len(fact) > MAX_LEN:
        return "over %d characters" % MAX_LEN
    if len(fact) < MIN_LEN:
        return "too short"
    if "|" in fact:
        return "contains |"
    if not (fact[0].isupper() or fact[0].isdigit()):
        return "does not start with a capital"
    if not fact.endswith("."):
        return "does not end with a full stop"
    if fact.lower().startswith(("did you know", "fun fact", "cat fact", "fact:")):
        return "starts with filler"
    return None


def key(fact):
    return re.sub(r"[^a-z0-9]", "", fact.lower())


def lua_string(fact):
    return '"' + fact.replace("\\", "\\\\").replace('"', '\\"') + '"'


def read_lines(path):
    if not os.path.exists(path):
        return None
    out = []
    for raw in io.open(path, encoding="utf-8", errors="replace"):
        line = clean(raw)
        if line:
            out.append(line)
    return out


def read_tiers():
    tiers = dict((t, []) for t in TIER_ORDER)
    lines = read_lines(os.path.join(FACTS_DIR, "tiers.txt")) or []
    current = None
    for line in lines:
        m = re.match(r"^\[(.+)\]$", line)
        if m:
            current = m.group(1)
            if current not in tiers:
                print("WARNING: unknown cat header %r, its facts are skipped" % current)
                current = None
            continue
        if current is None:
            print("WARNING: fact outside any cat header skipped: %s" % line)
            continue
        tiers[current].append(line)
    return tiers


seen, prefixes, dropped = {}, {}, []


def accept(fact, where):
    p = problem(fact)
    if p:
        dropped.append((where, p, fact))
        return False
    k = key(fact)
    if k in seen:
        dropped.append((where, "duplicate of: " + seen[k], fact))
        return False
    pre = k[:PREFIX]
    if pre in prefixes:
        dropped.append((where, "near duplicate of: " + prefixes[pre], fact))
        return False
    seen[k] = fact
    prefixes[pre] = fact
    return True


tiers = read_tiers()
cat_facts = []
cat_total = 0
for name in TIER_ORDER:
    kept = [f for f in tiers[name] if accept(f, name)]
    cat_total += len(kept)
    cat_facts.append((name, kept))

lanes = []
bank_total = 0
for lane, title in LANES:
    lines = read_lines(os.path.join(FACTS_DIR, lane + ".txt"))
    if lines is None:
        print("note: no %s.txt, lane skipped" % lane)
        continue
    kept = [f for f in lines if accept(f, lane)]
    bank_total += len(kept)
    lanes.append((lane, title, kept))

out = []
out.append("--[[-------------------------------------------------------------------------")
out.append("  CatXP fact bank. GENERATED by tools/build_facts.py from the text files in")
out.append("  tools/facts/ (one fact per line): add facts there and run the script, or")
out.append("  edit this file directly if the script is never going to run again.")
out.append("")
out.append("  ns.CAT_FACTS      one list per cat on the ladder, said on that cat's own")
out.append("                    promotions and demotions until each has been heard once")
out.append("  ns.GENERAL_FACTS  the bank: every other announcement, and every cat once its")
out.append("                    own list is used up, in a shuffled no-repeat order (Facts.lua)")
out.append("")
out.append("  Rules for a fact: plain ASCII, under 140 characters, a capital first letter,")
out.append("  a full stop at the end and never the | character, which WoW reads as a text")
out.append("  code. The tests check every line.")
out.append("---------------------------------------------------------------------------]]")
out.append("")
out.append("local ADDON_NAME, ns = ...")
out.append("")
out.append("ns.CAT_FACTS = {")
for name, kept in cat_facts:
    out.append('  ["%s"] = {' % name)
    for f in kept:
        out.append("    " + lua_string(f) + ",")
    out.append("  },")
out.append("}")
out.append("")
out.append("local bank = {}")
out.append("ns.GENERAL_FACTS = bank")
out.append("local function add(list) for i = 1, #list do bank[#bank + 1] = list[i] end end")
for lane, title, kept in lanes:
    out.append("")
    out.append("-- %s (%d)" % (title, len(kept)))
    out.append("add {")
    for f in kept:
        out.append("  " + lua_string(f) + ",")
    out.append("}")
out.append("")
out.append("-- %d facts in the bank, %d for the cats on the ladder." % (bank_total, cat_total))
out.append("")
io.open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(out))

for where, why, fact in dropped:
    print("dropped [%s] %s: %s" % (where, why, fact))
print("")
for name, kept in cat_facts:
    print("%-16s %d" % (name, len(kept)))
for lane, title, kept in lanes:
    print("%-16s %d" % (lane, len(kept)))
print("bank %d, cats %d, dropped %d -> %s" % (bank_total, cat_total, len(dropped), OUT))
